function photoUrl(name: string) {
  const src = PHOTO[name];
  if (!src) return null;
  if (src.startsWith("/")) return src;
  return `https://images.unsplash.com/${src}?auto=format&fit=crop&w=480&h=480&q=70`;
}

let n = 0;
function item(
  name: string,
  ingredients: string,
  allergens: string[],
  kcal: number,
  portion: string,
  priceTl: number,
): Product {
  n += 1;
  const slug = name
    .toLowerCase()
    .replace(/[^a-z0-9ğüşıöçâîû ]/gi, "")
    .trim()
    .replace(/\s+/g, "-");
  return {
    id: `p-${n}`,
    slug: `${slug}-${n}`,
    name,
    description: ingredients,
    priceCents: priceTl * 100,
    imageUrl: photoUrl(name),
    allergens,
    energyKcal: kcal,
    portionNote: portion,
    ingredientsNote: ingredients,
    isAvailable: true,
  };
}

